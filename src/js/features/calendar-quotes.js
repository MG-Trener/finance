  const DECK_KEY='finance.launchQuote.deck.v1';
  const CURRENT_KEY='finance.launchQuote.current.v1';

  function shuffledIndexes(){
    const items=Array.from({length:QUOTES.length},(_,index)=>index);
    for(let index=items.length-1;index>0;index--){
      const swap=Math.floor(Math.random()*(index+1));
      [items[index],items[swap]]=[items[swap],items[index]];
    }
    return items;
  }

  function readDeck(){
    try{
      const parsed=JSON.parse(localStorage.getItem(DECK_KEY)||'[]');
      if(!Array.isArray(parsed))return [];
      return parsed.filter(index=>Number.isInteger(index)&&index>=0&&index<QUOTES.length);
    }catch(_){
      return [];
    }
  }

  function selectLaunchQuote(){
    let deck=readDeck();
    const previous=Number(localStorage.getItem(CURRENT_KEY));
    if(!deck.length)deck=shuffledIndexes();
    if(deck.length>1&&Number.isInteger(previous)&&deck[deck.length-1]===previous){
      [deck[0],deck[deck.length-1]]=[deck[deck.length-1],deck[0]];
    }
    const index=deck.pop();
    try{
      localStorage.setItem(DECK_KEY,JSON.stringify(deck));
      localStorage.setItem(CURRENT_KEY,String(index));
    }catch(_ ){}
    return QUOTES[index]||QUOTES[0];
  }

  const launchQuote=selectLaunchQuote();

  function safe(value){
    if(typeof esc==='function')return esc(value);
    return String(value??'').replace(/[&<>'"]/g,char=>({'&':'&amp;','<':'&lt;','>':'&gt;',"'":'&#39;','"':'&quot;'}[char]));
  }

  function quoteMarkup(){
    return `<aside class="finance-launch-quote" aria-label="Цитата о деньгах"><span class="finance-launch-quote-text">«${safe(launchQuote.text)}»</span><span class="finance-launch-quote-author">— ${safe(launchQuote.author)}</span></aside>`;
  }

  function decorateCalendarMarkup(markup){
    if(typeof markup!=='string'||markup.includes('finance-launch-quote'))return markup;
    const needle='<div><h2 class="page-title">Календарь</h2><div class="page-subtitle">';
    if(!markup.includes(needle))return markup;
    return markup.replace(
      needle,
      `<div class="calendar-heading-copy"><h2 class="page-title">Календарь</h2>${quoteMarkup()}<div class="page-subtitle">`
    );
  }

